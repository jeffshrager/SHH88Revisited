#!/usr/bin/env python3
"""Generate SHH/BitGame/Exact.lean: exact expected steps in the three-bit game, as tables
checked against the system of SHH.Markov.HitSys, for the initial operators and for the initial
operators plus one chunk, at r = 0, 1/2, 1. Edit this generator, not the output.

    python3 tools/gen_exact.py
"""
import os, sys
from itertools import product
from fractions import Fraction as F
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bitgame import initial_ops, chunk, expected_steps, bits

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = 3
STATES = list(product((False, True), repeat=B))
GOAL = bits("001")
START = bits("000")
NEW = chunk(bits("000"), bits("110"))
CASES = [("r0", F(0), "(0 : ℚ)"), ("rHalf", F(1, 2), "(1/2 : ℚ)"), ("r1", F(1), "(1 : ℚ)")]


def lst(x):
    return "[" + ", ".join("true" if b else "false" for b in x) + "]"


def q(v):
    return f"({v.numerator}/{v.denominator} : ℚ)" if v.denominator != 1 else f"({v.numerator} : ℚ)"


def table(name, ops, r):
    rows = ", ".join(f"({lst(x)}, {q(expected_steps(ops, r, B, x, GOAL))})" for x in STATES)
    return f"def {name} : State → ℚ := fun x => (([{rows}] : List (State × ℚ)).lookup x).getD 0\n"


def main():
    base, plus = initial_ops(B), initial_ops(B) + [NEW]
    out = ['''import SHH.BitGame.Decision
import SHH.Markov.Hitting

/-!
# Exact expected steps in the three-bit game (generated by `tools/gen_exact.py`)

The game `000 → 001` with the six initial operators, and with one chunk added, `00? → 11?`
(the chunk of `000 → 110`). Each table is checked to satisfy the system for expected steps
(`SHH.Markov.HitSys`), and the chain is checked to be well formed with the goal reachable from
every state, so by `SHH.Markov.hit_unique` each table *is* the vector of expected steps.

The fan effect at the level of a single game: adding the chunk raises the expected steps
for this game at `r = 0` (7 → 133/15) and at `r = 1/2` (19/7 → 752538/208555), and leaves them
at 1 at `r = 1`. Whether learning helps *on average* is a different question (see
`notes/CLAIMS.md` and `tools/bitgame.py`: on the three-bit game every single chunk lowers the
mean expected steps at `r = 0` and `r = 1` and raises it at `r = 1/2`).
-/

namespace SHH.BitGame

open SHH.Markov

/-- The goal `001` and the start `000`. -/
def goal3 : State := ''' + lst(GOAL) + '''
def start3 : State := ''' + lst(START) + '''

/-- The initial operators, and the initial operators plus the chunk `00? → 11?`. -/
def opsBase : List Op := initialOps 3
def opsPlus : List Op := initialOps 3 ++ [chunk ''' + lst(bits("000")) + " " + lst(bits("110")) + ''']

/-- The chain of a decision procedure on the three-bit game is well formed: weights
nonnegative and summing to one, successors among the states, and the goal reachable. -/
structure WellFormed (ops : List Op) (r : ℚ) : Prop where
  nn : ∀ x ∈ allStates 3, ∀ yp ∈ stepDist ops r goal3 x, 0 ≤ yp.2
  mass : ∀ x ∈ allStates 3, x ≠ goal3 → ((stepDist ops r goal3 x).map Prod.snd).sum = 1
  closed : ∀ x ∈ allStates 3, ∀ yp ∈ stepDist ops r goal3 x, yp.1 ∈ allStates 3
  reach : ∀ x ∈ allStates 3, reachB (stepDist ops r goal3) goal3 8 x = true

/-- With a well-formed chain, a checked table is the unique vector of expected steps. -/
theorem steps_of_table (ops : List Op) (r : ℚ) (T : State → ℚ) (hw : WellFormed ops r)
    (hT : HitSys (allStates 3) (stepDist ops r goal3) goal3 T) :
    ∀ T', HitSys (allStates 3) (stepDist ops r goal3) goal3 T' → T' start3 = T start3 :=
  fun T' h' => hit_unique _ _ _ T' T (by decide) hw.nn hw.mass hw.closed
    (fun x hx => reachB_sound _ _ 8 x (hw.reach x hx)) h' hT start3 (by decide)

''']
    for tag, r, rs in CASES:
        for which, ops in [("Base", base), ("Plus", plus)]:
            nm = f"T_{tag}_{which}"
            out.append(table(nm, ops, r))
            out.append(f'''
theorem wf_{tag}_{which} : WellFormed ops{which} {rs} :=
  ⟨by decide +kernel, by decide +kernel, by decide +kernel, by decide +kernel⟩

theorem sys_{tag}_{which} : HitSys (allStates 3) (stepDist ops{which} {rs} goal3) goal3 {nm} :=
  ⟨by decide +kernel, by decide +kernel⟩

''')
    vals = {}
    for tag, r, rs in CASES:
        vals[tag] = (expected_steps(base, r, B, START, GOAL), expected_steps(plus, r, B, START, GOAL))
    out.append(f'''/-- **One chunk can slow a game down** (the fan effect, for a single game). In the game
`000 → 001`, adding the chunk `00? → 11?` raises the expected steps from 7 to 133/15 with no
decision procedure (`r = 0`) and from 19/7 to 752538/208555 with a mediocre one (`r = 1/2`), and
leaves them at 1 with a perfect one (`r = 1`). Every solution of the system has these values. -/
theorem chunk_slows_game :
    (∀ T, HitSys (allStates 3) (stepDist opsBase 0 goal3) goal3 T → T start3 = {q(vals["r0"][0])}) ∧
    (∀ T, HitSys (allStates 3) (stepDist opsPlus 0 goal3) goal3 T → T start3 = {q(vals["r0"][1])}) ∧
    (∀ T, HitSys (allStates 3) (stepDist opsBase (1/2) goal3) goal3 T → T start3 = {q(vals["rHalf"][0])}) ∧
    (∀ T, HitSys (allStates 3) (stepDist opsPlus (1/2) goal3) goal3 T → T start3 = {q(vals["rHalf"][1])}) ∧
    (∀ T, HitSys (allStates 3) (stepDist opsBase 1 goal3) goal3 T → T start3 = {q(vals["r1"][0])}) ∧
    (∀ T, HitSys (allStates 3) (stepDist opsPlus 1 goal3) goal3 T → T start3 = {q(vals["r1"][1])}) := by
  refine ⟨fun T h => ?_, fun T h => ?_, fun T h => ?_, fun T h => ?_, fun T h => ?_, fun T h => ?_⟩
  · rw [steps_of_table _ _ _ wf_r0_Base sys_r0_Base T h]; decide +kernel
  · rw [steps_of_table _ _ _ wf_r0_Plus sys_r0_Plus T h]; decide +kernel
  · rw [steps_of_table _ _ _ wf_rHalf_Base sys_rHalf_Base T h]; decide +kernel
  · rw [steps_of_table _ _ _ wf_rHalf_Plus sys_rHalf_Plus T h]; decide +kernel
  · rw [steps_of_table _ _ _ wf_r1_Base sys_r1_Base T h]; decide +kernel
  · rw [steps_of_table _ _ _ wf_r1_Plus sys_r1_Plus T h]; decide +kernel

end SHH.BitGame
''')
    open(os.path.join(ROOT, "SHH", "BitGame", "Exact.lean"), "w").write("".join(out))
    print("wrote SHH/BitGame/Exact.lean;", {k: (str(a), str(b)) for k, (a, b) in vals.items()})


if __name__ == "__main__" and len(sys.argv) == 1:
    main()


def gen_mean():
    xs = [[]]
    for _ in range(B):
        xs = [y for x in xs for y in ([False] + x, [True] + x)]
    global ALL3
    ALL3 = "[" + ", ".join(lst(x) for x in xs) + "]"
    """SHH/BitGame/ExactMean.lean: the mean expected steps over all 56 games of the three-bit
    game, with and without the chunk 00? -> 11?, at r = 0, 1/2, 1."""
    base, plus = initial_ops(B), initial_ops(B) + [NEW]
    out = ['''import SHH.BitGame.Exact

/-!
# The mean over all games of the three-bit game (generated by `tools/gen_exact.py`)

For each goal `g`, one table gives the expected steps from every start (`SHH.Markov.hit_unique`
makes it the unique solution). Averaging over the 56 games `s → g` with `s ≠ g`:

* `r = 0` (no decision procedure): the chunk `00? → 11?` **lowers** the mean;
* `r = 1/2` (mediocre): it **raises** the mean: the problem-solving fan effect;
* `r = 1` (perfect): it lowers the mean.

This is the pattern of the paper's Figure 1 (improvement at `r = 0` and `r = 1`, initial
degradation at `r = 1/2`), exact, in the bit game itself. It is also what the paper's tree
idealization gets wrong at `r = 0`, where the idealized walk shows a fan effect
(`SHH.GD.fan_pow2_zero`) and the real game does not. (`tools/bitgame.py`: the same holds for
every one of the 32 single chunks.)
-/

namespace SHH.BitGame

open SHH.Markov

/-- The chain toward goal `g` is well formed. -/
structure WellFormedG (ops : List Op) (r : ℚ) (g : State) : Prop where
  nn : ∀ x ∈ allStates 3, ∀ yp ∈ stepDist ops r g x, 0 ≤ yp.2
  mass : ∀ x ∈ allStates 3, x ≠ g → ((stepDist ops r g x).map Prod.snd).sum = 1
  closed : ∀ x ∈ allStates 3, ∀ yp ∈ stepDist ops r g x, yp.1 ∈ allStates 3
  reach : ∀ x ∈ allStates 3, reachB (stepDist ops r g) g 8 x = true

/-- The eight states, in `allStates` order. -/
theorem allStates_three : allStates 3 = ''' + ALL3 + ''' := by decide

/-- The mean of `T g s` over the 56 games `s → g`, `s ≠ g`. -/
def meanSteps (T : State → State → ℚ) : ℚ :=
  ((allStates 3).flatMap fun g => (allStates 3).filterMap fun s =>
    if s = g then none else some (T g s)).sum / 56

theorem table_unique (ops : List Op) (r : ℚ) (g : State) (hg : g ∈ allStates 3) (T : State → ℚ)
    (hw : WellFormedG ops r g) (hT : HitSys (allStates 3) (stepDist ops r g) g T) :
    ∀ T', HitSys (allStates 3) (stepDist ops r g) g T' → ∀ x ∈ allStates 3, T' x = T x :=
  fun T' h' x hx => hit_unique _ _ _ T' T hg hw.nn hw.mass hw.closed
    (fun y hy => reachB_sound _ _ 8 y (hw.reach y hy)) h' hT x hx

''']
    names = {}
    means = {}
    for tag, r, rs in CASES:
        for which, ops in [("Base", base), ("Plus", plus)]:
            tabs = []
            tot = F(0)
            for gi, g in enumerate(STATES):
                rows = ", ".join(f"({lst(x)}, {q(expected_steps(ops, r, B, x, g))})" for x in STATES)
                for x in STATES:
                    if x != g:
                        tot += expected_steps(ops, r, B, x, g)
                nm = f"M_{tag}_{which}_{gi}"
                tabs.append((nm, g))
                out.append(f"def {nm} : State → ℚ := fun x => (([{rows}] : List (State × ℚ)).lookup x).getD 0\n")
                out.append(f"theorem wf_{nm} : WellFormedG ops{which} {rs} {lst(g)} :=\n"
                           f"  ⟨by decide +kernel, by decide +kernel, by decide +kernel, by decide +kernel⟩\n")
                out.append(f"theorem sys_{nm} : HitSys (allStates 3) (stepDist ops{which} {rs} {lst(g)}) {lst(g)} {nm} :=\n"
                           f"  ⟨by decide +kernel, by decide +kernel⟩\n\n")
            names[(tag, which)] = tabs
            means[(tag, which)] = tot / 56
            # the combined table and the mean theorem
            cases = "\n".join(f"    else if g = {lst(g)} then {nm} s" for nm, g in tabs)
            out.append(f"def MT_{tag}_{which} : State → State → ℚ := fun g s =>\n    if False then 0\n{cases}\n    else 0\n\n")
            hyps = "\n".join(
                f"  have e{i} := table_unique _ _ {lst(g)} (by decide) _ wf_{nm} sys_{nm} (T {lst(g)}) (h {lst(g)} (by decide))"
                for i, (nm, g) in enumerate(tabs))
            out.append(f'''/-- The mean expected steps over all games, `{which}` operators, `r = {rs}`. -/
theorem mean_{tag}_{which} (T : State → State → ℚ)
    (h : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist ops{which} {rs} g) g (T g)) :
    meanSteps T = {q(means[(tag, which)])} := by
{hyps}
  have hT : ∀ g ∈ allStates 3, ∀ s ∈ allStates 3, T g s = MT_{tag}_{which} g s := by
    intro g hg s hs
    rw [allStates_three] at hg
    simp only [List.mem_cons, List.mem_nil_iff, or_false] at hg
    rcases hg with rfl | rfl | rfl | rfl | rfl | rfl | rfl | rfl <;>
      first | (rw [e0 s hs]; simp [MT_{tag}_{which}]) | (rw [e1 s hs]; simp [MT_{tag}_{which}]) |
        (rw [e2 s hs]; simp [MT_{tag}_{which}]) | (rw [e3 s hs]; simp [MT_{tag}_{which}]) |
        (rw [e4 s hs]; simp [MT_{tag}_{which}]) | (rw [e5 s hs]; simp [MT_{tag}_{which}]) |
        (rw [e6 s hs]; simp [MT_{tag}_{which}]) | (rw [e7 s hs]; simp [MT_{tag}_{which}])
  have : meanSteps T = meanSteps MT_{tag}_{which} := by
    unfold meanSteps
    congr 1
    congr 1
    apply List.flatMap_congr
    intro g hg
    apply List.filterMap_congr
    intro s hs
    split_ifs <;> simp [hT g hg s hs]
  rw [this]
  decide +kernel

''')
    m = {k: v for k, v in means.items()}
    out.append(f'''/-- **Figure 1's pattern, exact, in the three-bit game.** One chunk lowers the mean expected
steps over all games at `r = 0` ({float(m[("r0","Base")]):.4f} → {float(m[("r0","Plus")]):.4f}) and at `r = 1`
({float(m[("r1","Base")]):.4f} → {float(m[("r1","Plus")]):.4f}), and raises it at `r = 1/2`
({float(m[("rHalf","Base")]):.4f} → {float(m[("rHalf","Plus")]):.4f}): practice helps without a decision procedure
and with a perfect one, and hurts with a mediocre one. -/
theorem figure1_pattern_three (B0 P0 Bh Ph B1 P1 : State → State → ℚ)
    (hB0 : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsBase (0 : ℚ) g) g (B0 g))
    (hP0 : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsPlus (0 : ℚ) g) g (P0 g))
    (hBh : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsBase (1/2 : ℚ) g) g (Bh g))
    (hPh : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsPlus (1/2 : ℚ) g) g (Ph g))
    (hB1 : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsBase (1 : ℚ) g) g (B1 g))
    (hP1 : ∀ g ∈ allStates 3, HitSys (allStates 3) (stepDist opsPlus (1 : ℚ) g) g (P1 g)) :
    meanSteps P0 < meanSteps B0 ∧ meanSteps Bh < meanSteps Ph ∧ meanSteps P1 < meanSteps B1 := by
  rw [mean_r0_Base B0 hB0, mean_r0_Plus P0 hP0, mean_rHalf_Base Bh hBh, mean_rHalf_Plus Ph hPh,
    mean_r1_Base B1 hB1, mean_r1_Plus P1 hP1]
  norm_num

end SHH.BitGame
''')
    open(os.path.join(ROOT, "SHH", "BitGame", "ExactMean.lean"), "w").write("".join(out))
    print("wrote SHH/BitGame/ExactMean.lean;", {k: str(v) for k, v in means.items()})


if __name__ == "__main__" and len(sys.argv) > 1 and sys.argv[1] == "mean":
    gen_mean()
